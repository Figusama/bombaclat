BY_ID = {t[0]: {"id": t[0], "name": t[1], "violation": t[2], "normal": t[3], "in_dataset": t[4]} for t in TYPES}


def load_norms(path=CSV_PATH):
    """Возвращает {type_id: текст норматива} из CSV команды."""
    by_name = {}
    if Path(path).exists():
        for row in list(csv.reader(open(path, encoding="utf-8-sig")))[1:]:
            by_name[row[0].strip()] = row[4].strip() if len(row) > 4 else ""
    return {tid: by_name.get(BY_ID[tid]["name"], "") for tid in IDS}
